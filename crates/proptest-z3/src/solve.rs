/// How [hints](crate::Hint) are treated when filling holes (the solving strategy).
///
/// Both are deterministic: the same skeleton, hints and candidates give the same result. Use
/// [`Fill::Greedy`] by default, and try [`Fill::Optimal`] if the generated names look skewed.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[non_exhaustive]
pub enum Fill {
    /// The default. Solves with the hint of each hole as an assumption; on a conflict, drops the
    /// hint in the unsat core that is last in evaluation order and solves again (using a `QF_LIA`
    /// solver).
    ///
    /// It is fast. The choice of hints to drop is not optimal, so it may drop more hints than
    /// [`Fill::Optimal`]. Hints are given up from the later holes first, so holes evaluated earlier
    /// tend to get names closer to their hints.
    #[default]
    Greedy,
    /// Maximizes the number of hints kept (Z3's `Optimize`).
    ///
    /// As faithful to the hints as possible, but slow with many holes.
    Optimal,
}

/// The index of a hole in a solved result, numbered from 0 in **text order** (the order of
/// appearance in the output text).
///
/// It is different from the positions in evaluation order used inside rules ([`Binds`]).
/// [`Solved::events`] maps between them.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Hole(pub usize);

/// Information about a single hole after filling, returned by [`Solved::holes`] / [`Solved::hole`].
#[derive(Debug, Clone)]
#[non_exhaustive]
pub struct FilledHole {
    /// The namespace.
    pub space: Space,
    /// The role (`Def` / `Use` / `Kill`).
    pub role: Role,
    /// The name filled in.
    pub name: String,
    /// The position in [`Solved::text`] (in bytes).
    pub span: Range<usize>,
}

/// The result of filling the holes; the value generated by [`fill`](crate::FillExt::fill).
///
/// - [`text`](Solved::text): the text with holes filled in. Pass it to the code under test
/// - [`holes`](Solved::holes) / [`hole`](Solved::hole) / [`name`](Solved::name) /
///   [`span`](Solved::span): holes in text order, with their names and positions
/// - [`events`](Solved::events): holes in evaluation order
/// - [`target`](Solved::target): the definition a reference points to
/// - [`marks`](Solved::marks) / [`labels`](Solved::labels) / [`has`](Solved::has): recorded labels
#[derive(Clone)]
pub struct Solved {
    /// The text with the holes filled in. Pass this to the code under test.
    pub text: String,
    /// Holes, in text order.
    holes: Vec<FilledHole>,
    /// Holes, in evaluation order.
    events: Vec<Hole>,
    /// Labels whose conditions held.
    hits: Vec<(Option<Hole>, Tag)>,
    /// The definition each hole resolves to, in text order.
    targets: Vec<Option<Hole>>,
    pub(crate) declared: BTreeMap<String, bool>,
}

impl Solved {
    /// Returns all holes in text order, as `(Hole, &FilledHole)` pairs.
    pub fn holes(&self) -> impl Iterator<Item = (Hole, &FilledHole)> {
        self.holes.iter().enumerate().map(|(i, h)| (Hole(i), h))
    }

    /// Returns the information about `hole`.
    pub fn hole(&self, hole: Hole) -> &FilledHole {
        &self.holes[hole.0]
    }

    /// Returns the position of `hole` in [`text`](Solved::text) (in bytes). Same as `self.hole(hole).span`.
    pub fn span(&self, hole: Hole) -> Range<usize> {
        self.holes[hole.0].span.clone()
    }

    /// Returns the name filled into `hole`. Same as `self.hole(hole).name`.
    pub fn name(&self, hole: Hole) -> &str {
        &self.holes[hole.0].name
    }

    /// Returns the holes in evaluation order.
    ///
    /// `events()[i]` is the hole at position `i` in evaluation order inside rules ([`Binds`]).
    pub fn events(&self) -> &[Hole] {
        &self.events
    }

    /// Returns the definition hole that the reference `hole` points to.
    ///
    /// | Hole | Returns |
    /// | --- | --- |
    /// | `Use` | the visible definition its name points to |
    /// | `Kill` | the definition it kills |
    /// | a reference that is not visible, a definition | `None` |
    ///
    /// The rule is the same as [`visible`](crate::rules::visible) and agrees with
    /// [`resolves_to`](crate::rules::resolves_to) inside constraints: the last live definition of
    /// the name in evaluation order (the inner one under shadowing, the last one under redefinition
    /// in the same scope). Boundaries do not change the result. A `Kill` actually kills every
    /// definition of the name, but only this one is returned.
    ///
    /// Useful as the expected value for go-to-definition, find-references, rename and similar features.
    pub fn target(&self, hole: Hole) -> Option<Hole> {
        self.targets[hole.0]
    }

    /// Returns the marks recorded with [`Binds::mark`] that turned out true, as `(hole, label)` pairs.
    ///
    /// Only labels of type `L` are returned, in the order they were recorded.
    pub fn marks<L: Label>(&self) -> Vec<(Hole, L)> {
        self.hits
            .iter()
            .filter_map(|(h, t)| Some(((*h)?, t.get()?)))
            .collect()
    }

    /// Returns the labels of type `L` recorded with [`Binds::observe`] that turned out true.
    pub fn labels<L: Label>(&self) -> Vec<L> {
        self.hits
            .iter()
            .filter(|(h, _)| h.is_none())
            .filter_map(|(_, t)| t.get())
            .collect()
    }

    /// Returns whether the label `kind` recorded with [`Binds::observe`] turned out true.
    pub fn has<L: Label>(&self, kind: L) -> bool {
        self.labels::<L>().contains(&kind)
    }

    /// Returns the text with line numbers (starting at 0), without marks and labels.
    pub fn numbered(&self) -> String {
        (self.text.lines().enumerate())
            .map(|(i, l)| format!("{i:>3}| {l}\n"))
            .collect()
    }
}

impl Debug for Solved {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        writeln!(f, "Solved{{")?;
        write!(f, "{}", self.numbered())?;
        let (mut marks, mut labels) = (vec![], vec![]);
        for (h, t) in &self.hits {
            match h {
                Some(h) => marks.push(format!(
                    "{} @ {:?} `{}`",
                    t.name,
                    self.span(*h),
                    self.name(*h)
                )),
                None => labels.push(t.name.as_str()),
            }
        }
        if !marks.is_empty() {
            writeln!(f, " marks: {}", marks.join(", "))?;
        }
        if !labels.is_empty() {
            writeln!(f, " labels: {}", labels.join(", "))?;
        }
        write!(f, "}}")
    }
}

impl Skeleton {
    /// Fills the holes of this skeleton without proptest. Useful in unit tests and for checking a skeleton.
    ///
    /// For each hole, a name is chosen from its [hint](crate::Hint) and the candidates in `names`
    /// so that `rule` holds. Label statistics ([`label_stats`](crate::label_stats)) and rejection
    /// reasons ([`take_rejections`](crate::take_rejections)) are not counted.
    ///
    /// # Errors
    ///
    /// - `Failure::Unsat { core }` if the constraints cannot be satisfied. `core` holds the label
    ///   names of the [`Binds::require`]s in the unsat core
    /// - `Failure::Unknown { reason }` if Z3 cannot decide
    ///
    /// # Panics
    ///
    /// If `names` has no candidates for a namespace that has holes in the skeleton.
    ///
    /// # Examples
    ///
    /// ```
    /// # use proptest_z3::prelude::*;
    /// const VAR: Space = Space::new("var");
    ///
    /// let skeleton = Skeleton::steps([
    ///     frag!["let ", Frag::hole(VAR, Role::Def, Hint(0)), "\n"],
    ///     frag!["print ", Frag::hole(VAR, Role::Use, Hint(u16::MAX)), "\n"],
    /// ]);
    /// let names = Names::default().with(VAR, ["a", "b"]);
    ///
    /// // The reference hints at "b", but becomes "a" to satisfy `bound`
    /// let s = skeleton.solve(&names, Fill::Greedy, |binds| bound(binds, VAR)).unwrap();
    /// assert_eq!(s.text, "let a\nprint a\n");
    /// // There is only one reference, so two references cannot be invisible
    /// let failed = skeleton.solve(&names, Fill::Greedy, |binds| unbound(binds, VAR, 2));
    /// assert!(matches!(failed, Err(Failure::Unsat { .. })));
    /// ```
    pub fn solve(
        &self,
        names: &Names,
        fill: Fill,
        rule: impl Fn(&Binds) -> Bool,
    ) -> Result<Solved, Failure> {
        let frag = &self.0;
        let binds = Binds::new(frag);
        let count = |space: Space| {
            let n = names.get(space).len();
            assert!(n > 0, "no names for space `{}`", space.name());
            n
        };
        let mut hard: Vec<Bool> = (0..binds.len())
            .map(|i| constraint!(binds.name[i] in 0..count(binds.space[i])))
            .collect();
        hard.push(rule(&binds));
        let wishes: Vec<Bool> = (0..binds.len())
            .map(|i| {
                let hint = frag.holes[binds.hole[i]].hint.index(count(binds.space[i]));
                constraint!(binds.name[i] == hint)
            })
            .collect();
        let model = match fill {
            Fill::Greedy => greedy(&binds, &hard, wishes)?,
            Fill::Optimal => optimal(&binds, &hard, &wishes)?,
        };
        // Number in evaluation order → Name of the hole in text order
        let picked: Vec<usize> = model.get_as(&binds.name)?;
        let mut by_hole = vec![0; frag.holes.len()];
        for (i, &v) in picked.iter().enumerate() {
            by_hole[binds.hole[i]] = v;
        }
        // Resolve each reference with the same conditions as `visible`, now on concrete names.
        let target = |i: usize| {
            let same = |k: usize| picked[k] == picked[i];
            reaching_defs(&binds, i)
                .filter(|&k| same(k) && !kills_between(&binds, k, i).any(same))
                .max()
        };
        let mut targets = vec![None; frag.holes.len()];
        for i in (0..binds.len()).filter(|&i| binds.role[i].is_ref()) {
            targets[binds.hole[i]] = target(i).map(|k| Hole(binds.hole[k]));
        }
        // Insert into the text in order, recording the position of each hole
        let mut text = String::new();
        let mut holes = Vec::with_capacity(frag.holes.len());
        for piece in &frag.pieces {
            match piece {
                Piece::Text(s) => text.push_str(s),
                Piece::Hole(h) => {
                    let info = &frag.holes[*h];
                    let name = names.get(info.space)[by_hole[*h]].clone();
                    let start = text.len();
                    text.push_str(&name);
                    holes.push(FilledHole {
                        space: info.space,
                        role: info.role,
                        name,
                        span: start..text.len(),
                    });
                }
            }
        }
        // Reloading labels.
        let mut declared = BTreeMap::new();
        let mut hits = vec![];
        for (at, tag, cond) in &binds.records.borrow().labels {
            let value = (model.eval(cond, true).and_then(|b| b.as_bool())).ok_or_else(|| {
                Failure::Unknown {
                    reason: format!("cannot evaluate label {}", tag.name),
                }
            })?;
            *declared.entry(tag.name.clone()).or_insert(false) |= value;
            if value {
                hits.push((at.map(|i| Hole(binds.hole[i])), tag.clone()));
            }
        }
        Ok(Solved {
            text,
            holes,
            events: binds.hole.iter().map(|&h| Hole(h)).collect(),
            hits,
            targets,
            declared,
        })
    }
}

fn assert_hard(engine: &impl Engine, binds: &Binds, hard: &[Bool]) {
    engine.assert_all(hard);
    for (label, constraint) in &binds.records.borrow().required {
        engine.assert_labeled(label, constraint);
    }
}

fn optimal(binds: &Binds, hard: &[Bool], wishes: &[Bool]) -> Result<Model, Failure> {
    let opt = Optimize::new();
    assert_hard(&opt, binds, hard);
    let agree: Int = sum(wishes);
    opt.maximize(&agree);
    opt.solve()
}

fn greedy(binds: &Binds, hard: &[Bool], mut wishes: Vec<Bool>) -> Result<Model, Failure> {
    let solver = Solver::new_for_logic("QF_LIA").unwrap_or_default();
    assert_hard(&solver, binds, hard);
    loop {
        match solver.check_assumptions(&wishes) {
            z3::SatResult::Sat => {
                return solver.get_model().ok_or(Failure::Unknown {
                    reason: "no model".into(),
                });
            }
            z3::SatResult::Unsat => {
                let core = solver.get_unsat_core();
                match wishes.iter().rposition(|w| core.contains(w)) {
                    Some(d) => {
                        wishes.remove(d);
                    }
                    None => return solver.solve(),
                }
            }
            z3::SatResult::Unknown => {
                return Err(Failure::Unknown {
                    reason: solver.get_reason_unknown().unwrap_or_default(),
                });
            }
        }
    }
}
