use std::fmt::Display;

use proptest::prelude::*;

pub type Frac16 = u16;

/// A namespace: a set of names independent of the others. Create one for each kind of name that is
/// resolved separately, such as variables and functions.
///
/// Namespaces are identified by their string; two `Space`s created from the same string are the same
/// namespace. Names in different namespaces are unrelated even when the strings are equal. Every
/// predicate in [`rules`](crate::rules) only looks at holes of the same namespace.
///
/// # Examples
///
/// ```
/// # use proptest_z3::prelude::*;
/// const VAR: Space = Space::new("var");
/// const FUNC: Space = Space::new("func");
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Space(&'static str);

impl Space {
    /// Creates a namespace. Define it as a `const`.
    ///
    /// `name` is used as is in counterexamples and panic messages.
    pub const fn new(name: &'static str) -> Self {
        Self(name)
    }

    /// Returns the name of the namespace.
    pub fn name(self) -> &'static str {
        self.0
    }

    /// A strategy for a [`Frag`] containing a single hole with role `role`.
    ///
    /// The [hint](Hint) of the hole is chosen by proptest. Use this when the role is chosen by an
    /// argument; otherwise use [`def`](Space::def) / [`refer`](Space::refer) / [`kill`](Space::kill).
    pub fn hole(self, role: Role) -> impl Strategy<Value = Frag> {
        any::<Hint>().prop_map(move |hint| Frag::hole(self, role, hint))
    }

    /// A strategy for a hole that defines a name ([`Role::Def`]). Same as `hole(Role::Def)`.
    pub fn def(self) -> impl Strategy<Value = Frag> {
        self.hole(Role::Def)
    }

    /// A strategy for a hole that refers to a name ([`Role::Use`]). Same as `hole(Role::Use)`.
    pub fn refer(self) -> impl Strategy<Value = Frag> {
        self.hole(Role::Use)
    }

    /// A strategy for a hole that kills a name ([`Role::Kill`]). Same as `hole(Role::Kill)`.
    ///
    /// A kill hole is also a reference. A kill hides every definition of the same name, regardless
    /// of scopes (see [`Role::Kill`]).
    pub fn kill(self) -> impl Strategy<Value = Frag> {
        self.hole(Role::Kill)
    }
}

/// The role of a hole.
///
/// `Use` and `Kill` together are called **references** ([`Role::is_ref`]); both point to an
/// existing name. The visibility rules are collected in [`rules`](crate::rules).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum Role {
    /// Defines a name.
    ///
    /// A definition is visible from references that come later in evaluation order and are
    /// enclosed by the definition's scope. Within a step, definitions are moved to the end of the
    /// evaluation order, so they are not visible from the `Use`s of the same step, nor from scopes
    /// nested in that step.
    Def,
    /// Refers to a name.
    Use,
    /// Refers to a name and kills it at the same time.
    ///
    /// After this hole in evaluation order, no definition of the same name in the same namespace
    /// is visible. **Scopes and boundaries do not matter**: a kill in an inner scope also kills
    /// the outer definitions. A definition of the same name after the kill is visible again
    /// (within its scope).
    Kill,
}

impl Role {
    /// Returns `true` for a reference (`Use` or `Kill`).
    pub fn is_ref(self) -> bool {
        matches!(self, Role::Use | Role::Kill)
    }
}

/// The preferred name ("hint") of a hole.
///
/// It is a position among the candidates, as a fixed-point number in `[0, 1)` (`u16` / 65536).
/// Z3 picks the hinted name unless it conflicts with the constraints, so names that the constraints
/// leave open vary with proptest (see [`Fill`](crate::Fill)).
///
/// Hints are generated by proptest and shrink towards 0, so shrinking also moves names towards the
/// first candidate.
///
/// [`Space::def`] and friends create hints automatically, so you rarely touch them. They are used
/// when calling [`Frag::hole`] by hand.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub struct Hint(pub Frac16);

impl Hint {
    /// Returns the position `floor(size × h / 65536)` among `size` candidates.
    ///
    /// # Panics
    ///
    /// If `size` is 0.
    pub fn index(self, size: usize) -> usize {
        assert!(size > 0, "no candidates");
        // (h * n) / 65536
        ((size as u64 * self.0 as u64) >> Frac16::BITS) as usize
    }
}

impl Arbitrary for Hint {
    type Parameters = ();
    type Strategy = proptest::strategy::Map<proptest::num::u16::Any, fn(Frac16) -> Hint>;

    fn arbitrary_with(_: ()) -> Self::Strategy {
        any::<Frac16>().prop_map(Hint)
    }
}

#[derive(Debug, Clone)]
pub(crate) enum Piece {
    Text(String),
    Hole(usize),
}

#[derive(Debug, Clone)]
pub(crate) struct HoleInfo {
    pub space: Space,
    pub role: Role,
    pub hint: Hint,
    pub step: Option<usize>,
    pub scope: Option<usize>,
}

/// A fragment under construction: a sequence of text and holes, possibly with parts that are not
/// yet split into steps.
///
/// - Join fragments with [`frag!`](crate::frag!) or [`Frag::concat`]
/// - Make a nested scope with [`Frag::scope`] / [`Frag::boundary`]
/// - Finally, split into steps with [`Skeleton::steps`] to get a skeleton
///
/// `frag!` / [`Frag::concat`] / [`Frag::join`] do not create steps. A joined fragment becomes a
/// single step when it is closed by an outer call.
#[derive(Debug, Clone, Default)]
pub struct Frag {
    pub(crate) pieces: Vec<Piece>,
    pub(crate) holes: Vec<HoleInfo>,
    pub(crate) order: Vec<usize>,
    pub(crate) steps: usize,
    pub(crate) scope_parent: Vec<Option<usize>>,
    pub(crate) scope_boundary: Vec<bool>,
}

impl Frag {
    /// A fragment consisting of a single hole.
    ///
    /// Use this when you want to choose the hint yourself (for unit tests, for example).
    /// Usually the strategies such as [`Space::def`] are used instead.
    pub fn hole(space: Space, role: Role, hint: Hint) -> Self {
        Self {
            pieces: vec![Piece::Hole(0)],
            holes: vec![HoleInfo {
                space,
                role,
                hint,
                step: None,
                scope: None,
            }],
            order: vec![0],
            ..Default::default()
        }
    }

    /// A fragment consisting only of text.
    pub fn text(s: impl Into<String>) -> Self {
        Self {
            pieces: vec![Piece::Text(s.into())],
            ..Default::default()
        }
    }

    /// Concatenates fragments in order. Creates neither steps nor scopes.
    pub fn concat(parts: impl IntoIterator<Item = Frag>) -> Self {
        let mut out = Frag::default();
        for part in parts {
            let hole_base = out.holes.len();
            let step_base = out.steps;
            let scope_base = out.scope_parent.len();
            out.pieces.extend(part.pieces.into_iter().map(|p| match p {
                Piece::Hole(h) => Piece::Hole(hole_base + h),
                text => text,
            }));
            out.holes.extend(part.holes.into_iter().map(|h| HoleInfo {
                step: h.step.map(|s| step_base + s),
                scope: h.scope.map(|s| scope_base + s),
                ..h
            }));
            out.order
                .extend(part.order.into_iter().map(|h| hole_base + h));
            out.steps += part.steps;
            out.scope_parent.extend(
                part.scope_parent
                    .into_iter()
                    .map(|p| p.map(|s| scope_base + s)),
            );
            out.scope_boundary.extend(part.scope_boundary);
        }
        out
    }

    /// Concatenates fragments in order with `sep` between them. Useful for separated lists such as
    /// arguments.
    ///
    /// Like [`Frag::concat`], it creates neither steps nor scopes.
    ///
    /// # Examples
    ///
    /// ```
    /// # use proptest::prelude::*; use proptest_z3::prelude::*;
    /// const VAR: Space = Space::new("var");
    ///
    /// let call = prop::collection::vec(VAR.refer(), 0..4)
    ///     .prop_map(|args| frag!["print(", Frag::join(", ", args), ")"]);
    /// ```
    pub fn join(
        sep: impl IntoFrag + Clone,
        parts: impl IntoIterator<Item = impl IntoFrag>,
    ) -> Self {
        let mut out = vec![];
        for (i, part) in parts.into_iter().enumerate() {
            if i > 0 {
                out.push(sep.clone().into_frag());
            }
            out.push(part.into_frag());
        }
        Frag::concat(out)
    }

    /// Creates a nested scope. Each element of `steps` is closed as one step.
    ///
    /// - A name defined inside the scope is visible only from the scope and the scopes nested in
    ///   it, not from outer or sibling scopes
    /// - Names defined outside, earlier in evaluation order, are visible inside. Defining the same
    ///   name inside makes references inside point to the inner one (shadowing)
    /// - Seen from outside, the whole scope is part of the outer statement. Holes inside are
    ///   evaluated before the `Def`s and `Kill`s of the outer statement, so if `fn f { call f }`
    ///   is a single statement, `f` is not visible from its body
    /// - Kills ([`Role::Kill`]) cross scopes
    pub fn scope(steps: impl IntoIterator<Item = Frag>) -> Self {
        Frag::open(steps, false)
    }

    /// Creates a nested scope marked as a **boundary**. Use it for closure and function bodies.
    ///
    /// - Visibility, evaluation order and kills work exactly as for [`Frag::scope`]. Name
    ///   resolution ([`visible`](crate::rules::visible), [`Solved::target`](crate::Solved::target))
    ///   is unchanged
    /// - The only difference is that [`Binds::boundaries_between`](crate::Binds::boundaries_between)
    ///   counts how many boundaries a reference crosses to reach its definition. Captures
    ///   ([`captured`](crate::rules::captured)) are decided with it
    /// - The body is treated as evaluated where it is written (as if called on the spot). A kill
    ///   inside also affects references after the boundary. If `fn f [ call f ]` is a single
    ///   statement, `f` is not visible from its body
    /// - It nests freely with [`Frag::scope`]. Plain scopes are not counted as boundaries
    pub fn boundary(steps: impl IntoIterator<Item = Frag>) -> Self {
        Frag::open(steps, true)
    }

    fn open(steps: impl IntoIterator<Item = Frag>, boundary: bool) -> Self {
        let mut inner = Self::closed(steps);
        let new = Some(inner.scope_parent.len());
        for parent in inner.scope_parent.iter_mut().filter(|p| p.is_none()) {
            *parent = new;
        }
        inner.scope_parent.push(None);
        inner.scope_boundary.push(boundary);
        for hole in inner.holes.iter_mut().filter(|h| h.scope.is_none()) {
            hole.scope = new;
        }
        inner
    }

    fn closed(steps: impl IntoIterator<Item = Frag>) -> Self {
        Self::concat(steps.into_iter().map(Frag::close))
    }

    fn close(mut self) -> Self {
        let step = Some(self.steps);
        self.steps += 1;
        for hole in self.holes.iter_mut().filter(|h| h.step.is_none()) {
            hole.step = step;
        }
        let holes = &self.holes;
        self.order
            .sort_by_key(|&h| holes[h].scope.is_none() && holes[h].role != Role::Use);
        self
    }
}

/// Things that can be placed in [`frag!`](crate::frag!).
///
/// Implemented for:
///
/// | Type | Conversion |
/// | --- | --- |
/// | `Frag`, `&Frag` | as is (`&Frag` is cloned) |
/// | `Vec<T>`, `Option<T>` (`T: IntoFrag`) | elements joined in order; `None` is empty |
/// | tuples of 2 to 4 elements | elements joined in order |
/// | `&str`, `String`, `&String`, `char`, `bool`, integers, `f32`, `f64` | text from `to_string()` |
/// | [`Text<T>`](Text) (`T: Display`) | text from `to_string()` |
///
/// For your own types, implement this trait, or implement `Display` and wrap the value in [`Text`].
/// Holes do not survive `Display`, so implement this trait for types that contain holes.
pub trait IntoFrag {
    /// Converts into a fragment.
    fn into_frag(self) -> Frag;
}

impl IntoFrag for Frag {
    fn into_frag(self) -> Frag {
        self
    }
}
impl IntoFrag for &Frag {
    fn into_frag(self) -> Frag {
        self.clone()
    }
}
impl<T: IntoFrag> IntoFrag for Vec<T> {
    fn into_frag(self) -> Frag {
        Frag::concat(self.into_iter().map(IntoFrag::into_frag))
    }
}
impl<T: IntoFrag> IntoFrag for Option<T> {
    fn into_frag(self) -> Frag {
        self.map(IntoFrag::into_frag).unwrap_or_default()
    }
}

/// A wrapper for placing a `Display` value in [`frag!`](crate::frag!) as text.
///
/// The value becomes the text of `to_string()`; it cannot contain holes.
///
/// # Examples
///
/// ```
/// # use std::net::Ipv4Addr; use proptest_z3::prelude::*;
/// let host = frag!["connect ", Text(Ipv4Addr::LOCALHOST)];
/// ```
#[derive(Debug, Clone, Copy)]
pub struct Text<T>(pub T);

impl<T: Display> IntoFrag for Text<T> {
    fn into_frag(self) -> Frag {
        Frag::text(self.0.to_string())
    }
}

macro_rules! text_impl {
    ($($t:ty),*) => {$(
        impl IntoFrag for $t {
            fn into_frag(self) -> Frag {
                Frag::text(self.to_string())
            }
        }
    )*};
}
text_impl!(&str, String, &String, char, bool);
text_impl!(
    i8, i16, i32, i64, i128, isize, u8, u16, u32, u64, u128, usize, f32, f64
);

macro_rules! tuple_impl {
    ($($t:ident $i:tt),+) => {
        impl<$($t: IntoFrag),+> IntoFrag for ($($t,)+) {
            fn into_frag(self) -> Frag {
                Frag::concat([$(self.$i.into_frag()),+])
            }
        }
    };
}
tuple_impl!(T1 0, T2 1);
tuple_impl!(T1 0, T2 1, T3 2);
tuple_impl!(T1 0, T2 1, T3 2, T4 3);

/// A finished skeleton: the structure of an input with holes, where every hole belongs to a step.
#[derive(Debug, Clone)]
pub struct Skeleton(pub(crate) Frag);

impl Skeleton {
    /// Closes each element of `steps` as one step and completes the skeleton. This is the only way
    /// to create a skeleton.
    ///
    /// A step is the unit after which defined names become visible; split at the statements of
    /// your language. Steps are evaluated in order. Within a step, `Use`s and the holes of nested
    /// scopes are evaluated first, then `Def`s and `Kill`s. See [`rules`](crate::rules) for details.
    pub fn steps(steps: impl IntoIterator<Item = Frag>) -> Self {
        Skeleton(Frag::closed(steps))
    }

    /// Returns the number of holes.
    pub fn holes(&self) -> usize {
        self.0.holes.len()
    }
}
