use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Debug,
};

use proptest::{
    prelude::prop,
    strategy::{BoxedStrategy, Strategy, ValueTree},
};

use crate::Space;

/// Concrete name candidates per namespace.
///
/// Each namespace has a list of names, and the position in the list is the candidate index (the
/// value of [`Binds::name`](crate::Binds::name)).
///
/// [`fill`](crate::FillExt::fill) builds candidates from a [`NameSpec`], so you only create
/// `Names` directly when calling [`Skeleton::solve`](crate::Skeleton::solve) (in unit tests, for example).
#[derive(Debug, Clone, Default)]
pub struct Names {
    spaces: BTreeMap<Space, Vec<String>>,
}

impl Names {
    /// Returns the candidates of `space`, or an empty slice if it is not registered.
    pub fn get(&self, space: Space) -> &[String] {
        self.spaces.get(&space).map(Vec::as_slice).unwrap_or(&[])
    }

    /// Sets the candidates of `space` by hand (for unit tests and examples), replacing any existing ones.
    ///
    /// The order of the list is the candidate index. Duplicates and empty strings are not checked,
    /// so do not pass them.
    pub fn with(
        mut self,
        space: Space,
        names: impl IntoIterator<Item = impl Into<String>>,
    ) -> Self {
        self.spaces
            .insert(space, names.into_iter().map(Into::into).collect());
        self
    }
}

/// A strategy that generates name candidates (its value is [`Names`]). Add one namespace at a time.
///
/// Candidates are generated by proptest too, so shrinking also makes the names shorter and simpler.
///
/// The number of candidates greatly changes the inputs generated.
///
/// - With few, the same names are reused and redefinition and shadowing occur naturally (hard inputs
///   for a name resolver)
/// - With many, names spread out and the relations become simple
/// - With too few, constraints cannot be satisfied and rejections increase (e.g.
///   [`distinct_defs`](crate::rules::distinct_defs) cannot hold with more definitions than candidates)
///
/// Register every namespace that has holes in the skeleton; otherwise solving panics.
///
/// # Examples
///
/// ```
/// # use proptest_z3::prelude::*;
/// const VAR: Space = Space::new("var");
/// const FUNC: Space = Space::new("func");
///
/// fn names() -> NameSpec {
///     NameSpec::new()
///         .space(VAR, "[a-c]", 3)
///         .space(FUNC, "[a-c]", 3)
/// }
/// ```
#[derive(Clone, Default)]
pub struct NameSpec {
    spaces: BTreeMap<Space, BoxedStrategy<Vec<String>>>,
}

impl NameSpec {
    /// Creates an empty `NameSpec`.
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the candidates of `space` to `count` distinct names matching `regex`.
    ///
    /// The candidates are sorted lexicographically. Hints shrink towards 0, so shrinking moves names
    /// towards the lexicographically first candidate. If `regex` cannot produce `count` names, the
    /// candidates cannot be generated.
    ///
    /// # Panics
    ///
    /// If `regex` is not a valid regular expression, or if the namespace is registered twice.
    pub fn space(self, space: Space, regex: &str, count: usize) -> Self {
        let one = proptest::string::string_regex(regex).expect("invalid regex for names");
        let names = prop::collection::btree_set(one, count)
            .prop_map(|set| set.into_iter().collect::<Vec<_>>())
            .boxed();
        self.space_with(space, names)
    }

    /// Passes a strategy that generates the candidates of `space` directly.
    ///
    /// Use it for candidates that a regular expression cannot describe (such as avoiding keywords),
    /// or for fixed candidates (`Just(..)`). The order of the list is the candidate index.
    ///
    /// # Panics
    ///
    /// If the namespace is registered twice, or if a generated list contains an empty string or
    /// duplicates (at generation time).
    ///
    /// # Examples
    ///
    /// ```rust
    /// # use proptest::prelude::*; use proptest_z3::prelude::*;
    /// const VAR: Space = Space::new("var");
    /// const KEYWORDS: [&str; 3] = ["let", "print", "del"];
    ///
    /// let var = prop::collection::btree_set(
    ///     "[a-z]{1,4}".prop_filter("keyword", |s| !KEYWORDS.contains(&s.as_str())),
    ///     3,
    /// )
    /// .prop_map(|set| set.into_iter().collect::<Vec<_>>());
    /// let names = NameSpec::new().space_with(VAR, var.boxed());
    /// ```
    pub fn space_with(mut self, space: Space, names: BoxedStrategy<Vec<String>>) -> Self {
        let names = names
            .prop_map(move |names| {
                assert!(
                    names.iter().all(|name| !name.is_empty()),
                    "empty name in space `{}`",
                    space.name()
                );
                assert_eq!(
                    names.iter().collect::<BTreeSet<_>>().len(),
                    names.len(),
                    "duplicate names in space `{}`",
                    space.name()
                );
                names
            })
            .boxed();
        let prev = self.spaces.insert(space, names);
        assert!(prev.is_none(), "space `{}` registered twice", space.name());
        self
    }
}

impl Debug for NameSpec {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("NameSpec")
    }
}

impl Strategy for NameSpec {
    type Tree = Box<dyn ValueTree<Value = Names>>;
    type Value = Names;

    fn new_tree(
        &self,
        runner: &mut prop::test_runner::TestRunner,
    ) -> prop::strategy::NewTree<Self> {
        let keys: Vec<Space> = self.spaces.keys().copied().collect();
        let values: Vec<_> = self.spaces.values().cloned().collect();
        values
            .prop_map(move |all| Names {
                spaces: keys.iter().copied().zip(all).collect(),
            })
            .boxed()
            .new_tree(runner)
    }
}
