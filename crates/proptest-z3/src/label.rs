use std::{any::Any, cell::RefCell, collections::BTreeMap, fmt::Debug, io::Write, sync::Arc};

use z3::ast::Bool;
use z3_toolkit::Failure;

/// Types usable as labels. Implemented for every type that is
/// `Copy + Debug + PartialEq + Send + Sync + 'static`.
///
/// Use your own enums or `&'static str`.
///
/// The **name** of a label is the string itself for `&'static str`, and the `Debug` output
/// otherwise. Occurrence counts ([`label_stats`]), rejection reasons ([`take_rejections`]) and the
/// `Debug` output of [`Solved`](crate::Solved) use this name. Labels of different types with the
/// same name are counted as one. [`Solved::marks`](crate::Solved::marks) /
/// [`Solved::labels`](crate::Solved::labels), on the other hand, filter by type.
pub trait Label: Copy + Debug + PartialEq + Send + Sync + 'static {}
impl<T: Copy + Debug + PartialEq + Send + Sync + 'static> Label for T {}

#[derive(Clone)]
pub(crate) struct Tag {
    kind: Arc<dyn Any + Send + Sync>,
    pub name: String,
}

impl Tag {
    pub fn new<L: Label>(kind: L) -> Self {
        let name = match (&kind as &dyn Any).downcast_ref::<&'static str>() {
            Some(s) => s.to_string(),
            None => format!("{kind:?}"),
        };
        Self {
            kind: Arc::new(kind),
            name,
        }
    }

    pub fn get<L: Label>(&self) -> Option<L> {
        self.kind.downcast_ref::<L>().copied()
    }
}

#[derive(Default)]
pub(crate) struct Records {
    pub labels: Vec<(Option<usize>, Tag, Bool)>,
    pub required: Vec<(String, Bool)>,
}

/// A way to ask a condition only when its preconditions hold. Implemented for `Bool`.
///
/// When one violation always brings another with it, counting the kinds with `exactly(1)` makes an
/// input with only one of them impossible, so that kind is never generated (and a warning about a
/// label that never occurred is printed). Asking one condition only when the other does not hold
/// makes the two violations independent.
///
/// # Examples
///
/// ```
/// # use proptest_z3::prelude::*;
/// const VAR: Space = Space::new("var");
///
/// #[derive(Debug, Clone, Copy, PartialEq)]
/// enum Bug { Killed, Undefined }
///
/// // Ask "undefined" only when the name is not killed; the two kinds become independent
/// let rule = |binds: &Binds| constraint!(
///     exactly(1) { for i in binds.refs(VAR) {
///         binds.mark(i, Bug::Killed, killed(binds, i)),
///         binds.mark(i, Bug::Undefined, (!visible(binds, i)).given([!killed(binds, i)])),
///     } },
/// );
pub trait Given {
    /// Returns the conjunction of `self` and every precondition in `guard`. If any precondition is
    /// false, the whole expression is false.
    fn given(self, guard: impl IntoIterator<Item = Bool>) -> Bool;
}

impl Given for Bool {
    fn given(self, guard: impl IntoIterator<Item = Bool>) -> Bool {
        let all: Vec<Bool> = std::iter::once(self).chain(guard).collect();
        Bool::and(&all)
    }
}

/// Statistics for a single label, returned by [`label_stats`] / [`take_label_stats`].
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub struct LabelStat {
    /// The name of the label (see [`Label`]).
    pub label: String,
    /// The number of cases in which the label was recorded (`mark` / `observe` was called).
    pub declared: usize,
    /// The number of cases in which the label turned true at least once.
    pub occurred: usize,
}

#[derive(Default)]
struct Stats {
    // (label name, (recorded case, case where it was true))
    labels: BTreeMap<String, (usize, usize)>,
    // (unsat core name, count)
    rejections: BTreeMap<Vec<String>, usize>,
}

thread_local! {
    static STATS: RefCell<Stats> = RefCell::default();
}

fn with_stats<T>(f: impl FnOnce(&mut Stats) -> T) -> T {
    STATS.with(|s| f(&mut s.borrow_mut()))
}

pub(crate) fn count_case(declared: &BTreeMap<String, bool>) {
    with_stats(|s| {
        for (name, &hit) in declared {
            let (decl, occ) = s.labels.entry(name.clone()).or_default();
            *decl += 1;
            *occ += hit as usize;
        }
    })
}

pub(crate) fn count_rejection(failure: &Failure) {
    let key = match failure {
        Failure::Unsat { core } => {
            let mut core = core.clone();
            core.sort();
            core
        }
        other => vec![format!("{other}")],
    };
    with_stats(|s| *s.rejections.entry(key).or_default() += 1);
}

fn to_stats(labels: &BTreeMap<String, (usize, usize)>) -> Vec<LabelStat> {
    (labels.iter())
        .map(|(label, &(declared, occurred))| LabelStat {
            label: label.clone(),
            declared,
            occurred,
        })
        .collect()
}

/// Returns per-label statistics of the cases generated so far on this thread, ordered by label name.
///
/// - Only cases newly generated by [`fill`](crate::FillExt::fill) are counted. Shrinking steps and
///   [`Skeleton::solve`](crate::Skeleton::solve) are not
/// - Statistics are per thread. The test harness runs each test on its own thread, so they are per test
///
/// Labels that never turned true are reported on standard error when the thread ends, even if the
/// test passed.
///
/// ```text
/// proptest-z3 warning: label `Killed` never occurred in 259 cases (test `tests::my_test`); is it implied by another violation? consider `given`
/// ```
///
/// Common causes: the structure cannot produce it, the violation is implied by another (separate
/// them with [`Given`]), other constraints forbid it, the name candidates are skewed, or the
/// condition is simply rare.
pub fn label_stats() -> Vec<LabelStat> {
    with_stats(|s| to_stats(&s.labels))
}

/// Returns [`label_stats`] and resets the statistics.
///
/// Labels that were reset are no longer reported when the thread ends.
pub fn take_label_stats() -> Vec<LabelStat> {
    with_stats(|s| to_stats(&std::mem::take(&mut s.labels)))
}

/// Returns the reasons for rejections on this thread so far, with their counts, and resets them.
///
/// - A reason is the set of label names of [`Binds::require`](crate::Binds::require) that appeared
///   in the unsat core (sorted by name)
/// - If only unnamed constraints (such as the value returned by the rule) conflict, the set is empty
/// - Failures other than unsat (such as unknown) are a single string: the displayed `Failure`
/// - The core returned by Z3 is not necessarily minimal
///
/// Only rejections during generation by [`fill`](crate::FillExt::fill) are counted.
pub fn take_rejections() -> Vec<(Vec<String>, usize)> {
    with_stats(|s| std::mem::take(&mut s.rejections).into_iter().collect())
}

impl Drop for Stats {
    fn drop(&mut self) {
        let thread = std::thread::current();
        let mut err = std::io::stderr().lock();
        for s in to_stats(&self.labels)
            .into_iter()
            .filter(|s| s.occurred == 0)
        {
            let _ = writeln!(
                err,
                "proptest-z3 warning: label `{}` never occurred in {} cases (test `{}`); \
             is it implied by another violation? consider `given`",
                s.label,
                s.declared,
                thread.name().unwrap_or("?")
            );
        }
    }
}
